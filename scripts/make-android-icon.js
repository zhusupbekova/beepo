// Draws Beepo's happy face as the Android adaptive icon (vector drawables, crisp at any size):
//   android/app/src/main/res/drawable/ic_launcher_{foreground,monochrome}.xml
//   android/app/src/main/res/mipmap-anydpi-v26/ic_launcher.xml (+ background color)
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";

await import("../extension/render/sprite.js");
const sprites = JSON.parse(readFileSync(new URL("../extension/data/sprites.json", import.meta.url)));
const { grid, palette } = globalThis.BeepoSprite.compose({ sprites }, { mood: "happy" });
const res = new URL("../android/app/src/main/res/", import.meta.url);

// Crop to the pixels Beepo uses.
const ys = grid.flatMap((r, y) => (r.some((c) => c !== ".") ? [y] : []));
const xs = grid[0].map((_, x) => x).filter((x) => grid.some((r) => r[x] !== "."));
const [y0, y1, x0, x1] = [ys[0], ys.at(-1), xs[0], xs.at(-1)];

// Adaptive icons are 108 units; only the middle ~66 is sure to show, so Beepo gets 60 of it.
const SIZE = 108;
const cell = Math.floor(60 / Math.max(y1 - y0 + 1, x1 - x0 + 1));
const ox = (SIZE - (x1 - x0 + 1) * cell) / 2;
const oy = (SIZE - (y1 - y0 + 1) * cell) / 2;

/** One path per color: a square per pixel. `pick` maps a palette key to a color (or null to skip). */
function vector(pick) {
  const paths = new Map();
  for (let y = y0; y <= y1; y++) {
    for (let x = x0; x <= x1; x++) {
      const color = pick(grid[y][x]);
      if (!color) continue;
      const d = `M${ox + (x - x0) * cell},${oy + (y - y0) * cell}h${cell}v${cell}h-${cell}z`;
      paths.set(color, (paths.get(color) || "") + d);
    }
  }
  const body = [...paths].map(([color, d]) => `    <path android:fillColor="${color}" android:pathData="${d}" />`).join("\n");
  return `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/make-android-icon.js from data/sprites.json. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="${SIZE}"
    android:viewportHeight="${SIZE}">
${body}
</vector>
`;
}

mkdirSync(new URL("drawable/", res), { recursive: true });
mkdirSync(new URL("mipmap-anydpi-v26/", res), { recursive: true });
mkdirSync(new URL("values/", res), { recursive: true });

writeFileSync(new URL("drawable/ic_launcher_foreground.xml", res), vector((c) => (c === "." ? null : palette[c])));
// Themed icons are one color: leave the dark screen out so the eyes and smile show.
writeFileSync(new URL("drawable/ic_launcher_monochrome.xml", res), vector((c) => (c === "." || c === "s" ? null : "#FF000000")));
writeFileSync(
  new URL("values/ic_launcher_background.xml", res),
  `<?xml version="1.0" encoding="utf-8"?>\n<resources>\n    <color name="ic_launcher_background">#F4F1E8</color>\n</resources>\n`,
);
writeFileSync(
  new URL("mipmap-anydpi-v26/ic_launcher.xml", res),
  `<?xml version="1.0" encoding="utf-8"?>
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/ic_launcher_background" />
    <foreground android:drawable="@drawable/ic_launcher_foreground" />
    <monochrome android:drawable="@drawable/ic_launcher_monochrome" />
</adaptive-icon>
`,
);
console.log(`android icon: ${x1 - x0 + 1}×${y1 - y0 + 1} px at ${cell} units`);
